// 팔레트 스왑용 인덱스 스프라이트. 32x32 픽셀 아트 캐릭터 한 장이고, 색 대신 R 에 색 번호(0~7)를 담는다.
// 번호 i 는 i / 7 로 저장해 0~1 회색 계단이 된다. G, B 도 같은 값을 넣어 PNG 를 열면 회색 그림으로 보인다.
// 데이터 텍스처라 sRGB 를 끄고(linear) 포인트 필터로 읽는다.
//
// Unity 기본 임포트는 압축(BC, ASTC)이라 4x4 텍셀 블록 안의 값이 서로 섞여 색 번호가 틀어진다.
// 그래서 아트 1픽셀을 4x4 텍셀로 키워(128x128) 블록 하나가 언제나 한 값만 갖게 했다. 압축을 꺼도 결과는 같다.

// 색 번호: 0 외곽선, 1 옷 그림자, 2 옷, 3 옷 밝은 면, 4 머리카락, 5 피부, 6 보조색(머리띠, 스카프, 허리띠, 신발), 7 눈 하이라이트
// 왼쪽 절반(16칸)만 그리고 오른쪽은 거울로 채운다. '.' 은 투명.
const LEFT = [
  '................',
  '................',
  '..........000000',
  '........00444444',
  '.......044444444',
  '......0444444444',
  '......0444444444',
  '.....04444444444',
  '.....06666666666',
  '.....04455555555',
  '.....04555555555',
  '.....04555075555',
  '.....04555005555',
  '......0555555555',
  '......0555555550',
  '.......005555555',
  '........00666666',
  '.......066666666',
  '......0222666666',
  '.....02222226666',
  '....022222222226',
  '....022202222222',
  '....022202222222',
  '....055066666666',
  '....000022222222',
  '........02222222',
  '........01111110',
  '........01111110',
  '.......06666660.',
  '.......06666660.',
  '.......00000000.',
  '................',
]

const ART = 32
const COLORS = 8

for (const row of LEFT) if (row.length !== ART / 2) throw new Error(`행 길이가 16 이 아니다: ${row}`)

// 거울로 채운 뒤 옷에 빛 방향을 넣는다. 왼쪽 위에서 빛이 온다고 보고 왼쪽은 밝은 면(3), 오른쪽은 그림자(1)로 바꾼다.
const GRID = LEFT.map(left => {
  const cells = [...left, ...[...left].reverse()]
  return cells.map((c, x) => {
    if (c === '2' && x <= 10) return '3'
    if (c === '2' && x >= 20) return '1'
    return c
  })
})

export default {
  file: 'Assets/Shaders/palette-swap-lut/PaletteSwapLutIndex.png',
  size: 128,
  alpha: true,
  shade(u, v) {
    const c = GRID[Math.floor(v * ART)][Math.floor(u * ART)]
    if (c === '.') return [0, 0, 0, 0]
    const value = Number(c) / (COLORS - 1)
    return [value, value, value, 1]
  },
}
